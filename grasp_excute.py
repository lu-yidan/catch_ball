def vision_center_to_arm_mm(
    center_mm: np.ndarray,
    scale: np.ndarray | None = None,
) -> np.ndarray:
    """
    soft_arm_center (视觉 JSON, mm) -> 臂基坐标系.

    臂系: +X 侧向, +Y 向下, -Z 朝相机; 勿再把前向误当成 +Y.
    默认 scale=[1,1,1]；若视觉 Z 与臂 -Z 反号，设 scale[2]=-1.
    """
    center_mm = np.asarray(center_mm, dtype=float).reshape(3)
    if scale is None:
        scale = DEFAULT_VISION_TO_ARM_SCALE
    return center_mm * np.asarray(scale, dtype=float)


def motor_pull_unit_xz(phi_deg: float) -> np.ndarray:
    """+motor 步进在 XZ 弯曲平面内的单位方向 u(phi) = [cos(phi), sin(phi)]。"""
    r = np.deg2rad(float(phi_deg))
    return np.array([np.cos(r), np.sin(r)], dtype=float)


def _motor_unit_2d(phi_deg: float) -> np.ndarray:
    return motor_pull_unit_xz(phi_deg)


def motor_steps_to_bend_delta_xz(
    motor_steps: dict[int, int] | list[int],
    steps_per_degree: float = DEFAULT_REF_STEPS_PER_DEGREE,
) -> np.ndarray:
    """多电机步进合成的 XZ 弯曲增量 [dX, dZ]（度·方向）。"""
    delta = np.zeros(2, dtype=float)
    if isinstance(motor_steps, dict):
        items = motor_steps.items()
    else:
        items = ((i + 1, motor_steps[i]) for i in range(min(6, len(motor_steps))))
    for motor_id, steps in items:
        phi = MOTOR_POSITIVE_PULL_PHI_DEG.get(int(motor_id))
        if phi is None:
            continue
        dtheta = float(steps) / float(steps_per_degree)
        delta += dtheta * motor_pull_unit_xz(phi)
    return delta


def rope_phi_to_marker_plane_deg(phi_rope_deg: float) -> float:
    """绳组 XZ 平面 phi -> CSV Plane* 列（GP marker / XOY 约定）。"""
    return (float(phi_rope_deg) + MARKER_PLANE_OFFSET_FROM_ROPE_PHI_DEG) % 360.0


def marker_plane_to_rope_phi_deg(phi_marker_deg: float) -> float:
    """CSV Plane* -> 绳组 XZ phi。"""
    return (float(phi_marker_deg) - MARKER_PLANE_OFFSET_FROM_ROPE_PHI_DEG) % 360.0


def bend_dir_3d_inverted_from_phi(phi_deg: float, tangent: np.ndarray) -> np.ndarray:
    """
    倒立臂 PCC：弯曲平面 XZ，方向 [cos(phi), 0, sin(phi)]，投影到法平面。
    主切线沿 +Y；勿用 GP 正立系 [sin(phi), cos(phi), 0]。
    """
    beta = np.deg2rad(float(phi_deg))
    plane_dir = np.array([np.cos(beta), 0.0, np.sin(beta)], dtype=float)
    bend_dir = plane_dir - float(np.dot(plane_dir, tangent)) * tangent
    norm = float(np.linalg.norm(bend_dir))
    if norm < 1e-9:
        fallback = np.array([1.0, 0.0, 0.0], dtype=float)
        bend_dir = fallback - float(np.dot(fallback, tangent)) * tangent
        norm = float(np.linalg.norm(bend_dir))
    return bend_dir / max(norm, 1e-12)


def fk_inverted_pcc_centerline(
    pose_deg: np.ndarray,
    base_mm: np.ndarray | None = None,
    segment_lengths_mm: np.ndarray | None = None,
    *,
    theta_sign: float = ROPE_PLANNER_THETA_SIGN,
    points_per_segment: int = 16,
) -> np.ndarray:
    """
    倒立软体臂绳组 PCC 正运动学（臂系: +Y 主轴，XZ 弯曲）。

    pose: [Plane1, Plane2, Plane3, Theta1, Theta2, Theta3]（绳组 phi，非 CSV 原值）
    """
    if base_mm is None:
        base_mm = DEFAULT_ARM_BASE_MM
    if segment_lengths_mm is None:
        segment_lengths_mm = SEGMENT_LENGTHS_MM

    pose_deg = np.asarray(pose_deg, dtype=float)
    base_mm = np.asarray(base_mm, dtype=float).reshape(3)
    segment_lengths_mm = np.asarray(segment_lengths_mm, dtype=float)

    phi_deg = pose_deg[0:3]
    theta_deg = pose_deg[3:6] * float(theta_sign)

    pts: list[np.ndarray] = [base_mm.copy()]
    position = base_mm.copy()
    tangent = np.array([0.0, 1.0, 0.0], dtype=float)

    for seg_i in range(3):
        alpha = np.deg2rad(float(theta_deg[seg_i]))
        length = float(segment_lengths_mm[seg_i])
        bend_dir = bend_dir_3d_inverted_from_phi(float(phi_deg[seg_i]), tangent)

        for i in range(1, points_per_segment + 1):
            frac = i / points_per_segment
            alpha_i = alpha * frac
            length_i = length * frac
            if abs(alpha) < 1e-9:
                point = position + tangent * length_i
            else:
                radius = length / alpha
                point = (
                    position
                    + radius * np.sin(alpha_i) * tangent
                    + radius * (1.0 - np.cos(alpha_i)) * bend_dir
                )
            pts.append(point.copy())

        if abs(alpha) < 1e-9:
            position = position + tangent * length
        else:
            radius = length / alpha
            position = (
                position
                + radius * np.sin(alpha) * tangent
                + radius * (1.0 - np.cos(alpha)) * bend_dir
            )
            tangent = np.cos(alpha) * tangent + np.sin(alpha) * bend_dir
            tangent = tangent / max(float(np.linalg.norm(tangent)), 1e-12)

    return np.asarray(pts, dtype=float)


def _planned_bend_xz(pose: np.ndarray, phi_idx: int, theta_idx: int) -> np.ndarray:
    """XZ 弯曲向量 [X分量, Z分量] = theta * u(phi)。"""
    phi_deg = float(pose[phi_idx])
    theta_deg = float(pose[theta_idx])
    return float(theta_deg) * motor_pull_unit_xz(phi_deg)


def _planned_bend_xy(pose: np.ndarray, phi_idx: int, theta_idx: int) -> np.ndarray:
    """Backward-compatible alias (bend in XZ for inverted arm)."""
    return _planned_bend_xz(pose, phi_idx, theta_idx)


def _decompose_bend_2d_to_rope_thetas(
    delta_bend_2d: np.ndarray,
    phi_a_deg: float,
    phi_b_deg: float,
) -> tuple[float, float]:
    """Solve delta_bend = dtheta_a * u(phi_a) + dtheta_b * u(phi_b) in XZ."""
    m = np.column_stack([_motor_unit_2d(phi_a_deg), _motor_unit_2d(phi_b_deg)])
    dtheta_a, dtheta_b = np.linalg.solve(m, np.asarray(delta_bend_2d, dtype=float))
    return float(dtheta_a), float(dtheta_b)


def _decompose_bend_xy_to_rope_thetas(
    delta_bend_xy: np.ndarray,
    phi_a_deg: float,
    phi_b_deg: float,
) -> tuple[float, float]:
    return _decompose_bend_2d_to_rope_thetas(delta_bend_xy, phi_a_deg, phi_b_deg)


def _theta_delta_to_step(delta_theta_deg: float, scale: float, min_step_delta: int) -> int:
    step = int(round(delta_theta_deg * scale))
    if abs(step) < min_step_delta:
        return 0
    return step


