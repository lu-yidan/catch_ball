def motor14_in_grasp_range(motor1_steps: int, motor4_steps: int) -> bool:
    """Valid section-3 grasp: each motor engaged, sum of pulls below 15000."""
    a1, a4 = abs(int(motor1_steps)), abs(int(motor4_steps))
    return (
        a1 > MOTOR14_MIN_ABS_STEPS
        and a1 < MOTOR14_MAX_ABS_STEPS
        and a4 > MOTOR14_MIN_ABS_STEPS
        and a4 < MOTOR14_MAX_ABS_STEPS
        and (a1 + a4) < MOTOR14_MAX_SUM_ABS_STEPS
    )


def motor14_grasp_penalty(motor1_steps: int, motor4_steps: int) -> float:
    """Soft penalty when motor1/4 leave the feasible grasp envelope."""
    a1, a4 = abs(int(motor1_steps)), abs(int(motor4_steps))
    penalty = 0.0
    for a in (a1, a4):
        if a <= MOTOR14_MIN_ABS_STEPS:
            penalty += 420.0 * (MOTOR14_MIN_ABS_STEPS + 1 - a)
        if a >= MOTOR14_MAX_ABS_STEPS:
            penalty += 420.0 * (a - MOTOR14_MAX_ABS_STEPS + 1)
    sum_abs = a1 + a4
    if sum_abs >= MOTOR14_MAX_SUM_ABS_STEPS:
        penalty += 520.0 * (sum_abs - MOTOR14_MAX_SUM_ABS_STEPS + 1)
    return penalty


def motor14_steps_to_bend_delta(
    motor1_steps: int,
    motor4_steps: int,
    steps_per_degree: float = DEFAULT_REF_STEPS_PER_DEGREE,
) -> np.ndarray:
    """motor1+ @180°->-X, motor4+ @270°->-Z；返回 XZ 弯曲增量。"""
    return motor_steps_to_bend_delta_xz(
        {1: motor1_steps, 4: motor4_steps},
        steps_per_degree=steps_per_degree,
    )


def bend_delta_to_motor14_steps(
    delta_bend_xy: np.ndarray,
    steps_per_degree: float = DEFAULT_REF_STEPS_PER_DEGREE,
) -> tuple[int, int]:
    dtheta1, dtheta4 = _decompose_bend_xy_to_rope_thetas(
        np.asarray(delta_bend_xy, dtype=float),
        SECTION3_ROPE_PHI1_DEG,
        SECTION3_ROPE_PHI4_DEG,
    )
    return (
        int(round(dtheta1 * steps_per_degree)),
        int(round(dtheta4 * steps_per_degree)),
    )


def project_motor14_to_grasp_range(motor1_steps: int, motor4_steps: int) -> tuple[int, int]:
    """Scale/clamp motor steps into (6500,8000) each with |m1|+|m4| < 15000."""
    m1, m4 = int(motor1_steps), int(motor4_steps)
    if m1 == 0 and m4 == 0:
        return REF_GRASP_MOTOR1_STEPS, REF_GRASP_MOTOR4_STEPS

    for _ in range(24):
        a1, a4 = abs(m1), abs(m4)
        if a1 == 0 and a4 == 0:
            return REF_GRASP_MOTOR1_STEPS, REF_GRASP_MOTOR4_STEPS

        if a1 + a4 >= MOTOR14_MAX_SUM_ABS_STEPS:
            scale = (MOTOR14_MAX_SUM_ABS_STEPS - 1) / max(a1 + a4, 1)
            m1 = int(round(m1 * scale))
            m4 = int(round(m4 * scale))
            continue

        changed = False
        if a1 <= MOTOR14_MIN_ABS_STEPS:
            m1 = int(round(np.sign(m1) or -1) * (MOTOR14_MIN_ABS_STEPS + 1))
            changed = True
        if a4 <= MOTOR14_MIN_ABS_STEPS:
            m4 = int(round(np.sign(m4) or 1) * (MOTOR14_MIN_ABS_STEPS + 1))
            changed = True
        if a1 >= MOTOR14_MAX_ABS_STEPS:
            m1 = int(round(np.sign(m1) or -1) * (MOTOR14_MAX_ABS_STEPS - 1))
            changed = True
        if a4 >= MOTOR14_MAX_ABS_STEPS:
            m4 = int(round(np.sign(m4) or 1) * (MOTOR14_MAX_ABS_STEPS - 1))
            changed = True
        if not changed:
            break
    return m1, m4


def maximize_motor14_for_bend_direction(
    dir_2d: np.ndarray,
    steps_per_degree: float = DEFAULT_REF_STEPS_PER_DEGREE,
) -> tuple[int, int]:
    """Pick motor1/4 in grasp range to maximize bend along dir_2d in XZ."""
    dir_2d = np.asarray(dir_2d, dtype=float).reshape(2)
    norm = float(np.linalg.norm(dir_2d))
    if norm < 1e-9:
        dir_2d = np.array([0.0, -1.0], dtype=float)
    else:
        dir_2d = dir_2d / norm

    dtheta1, dtheta4 = _decompose_bend_2d_to_rope_thetas(
        dir_2d, SECTION3_ROPE_PHI1_DEG, SECTION3_ROPE_PHI4_DEG
    )
    if abs(dtheta1) < 1e-9 and abs(dtheta4) < 1e-9:
        return REF_GRASP_MOTOR1_STEPS, REF_GRASP_MOTOR4_STEPS

    scale = float("inf")
    for dtheta in (dtheta1, dtheta4):
        if abs(dtheta) < 1e-9:
            continue
        scale = min(scale, (MOTOR14_MAX_ABS_STEPS - 1) / (abs(dtheta) * steps_per_degree))
    scale = min(scale, (MOTOR14_MAX_SUM_ABS_STEPS - 1) / (abs(dtheta1) + abs(dtheta4)) / steps_per_degree)

    m1 = int(round(dtheta1 * scale * steps_per_degree))
    m4 = int(round(dtheta4 * scale * steps_per_degree))
    return project_motor14_to_grasp_range(m1, m4)


def _ball_dir_yz_arm(
    ball_center_mm: np.ndarray,
    base_mm: np.ndarray | None = None,
    approach: str = "side",
    vision_to_arm_scale: np.ndarray | None = None,
) -> np.ndarray:
    """Deprecated name; returns unit direction in XZ bend plane toward the ball."""
    ball_arm = vision_center_to_arm_mm(ball_center_mm, vision_to_arm_scale)
    if base_mm is None:
        base_arm = DEFAULT_ARM_BASE_MM.copy()
    else:
        base_arm = vision_center_to_arm_mm(base_mm, vision_to_arm_scale)
    if approach == "top-down":
        return np.array([0.0, 0.0], dtype=float)
    if approach == "below":
        return np.array([0.0, 0.0], dtype=float)

    dir_xz = np.array(
        [ball_arm[0] - base_arm[0], ball_arm[2] - base_arm[2]],
        dtype=float,
    )
    norm = float(np.linalg.norm(dir_xz))
    if norm < 1e-6:
        return np.array([0.0, -1.0], dtype=float)
    return dir_xz / norm


def target_section3_bend_delta_for_ball(
    ball_center_mm: np.ndarray,
    robot_base_mm: np.ndarray,
    approach: str = "side",
    vision_to_arm_scale: np.ndarray | None = None,
) -> np.ndarray:
    """Section-3 bend in XZ toward ball (inverted arm frame)."""
    dir_xz = _ball_dir_yz_arm(ball_center_mm, robot_base_mm, approach, vision_to_arm_scale)
    m1, m4 = maximize_motor14_for_bend_direction(dir_xz)
    return motor14_steps_to_bend_delta(m1, m4)


def section3_pose_from_grasp_motor14(
    home_pose: np.ndarray,
    motor1_steps: int,
    motor4_steps: int,
    steps_per_degree: float = DEFAULT_REF_STEPS_PER_DEGREE,
) -> np.ndarray:
    home_pose = np.asarray(home_pose, dtype=float)
    delta = motor14_steps_to_bend_delta(motor1_steps, motor4_steps, steps_per_degree)
    return apply_section3_bend_xy(home_pose, section3_bend_xy(home_pose) + delta)


def plane_phi_from_xz_mm(
    x_mm: float,
    z_mm: float,
    phi_offset_deg: float = SECTION12_PHI_OFFSET_DEG,
) -> float:
    """Plane angle for inverted arm: phi=atan2(Z, X)+offset in XZ bend plane."""
    phi_deg = float(np.degrees(np.arctan2(float(z_mm), float(x_mm)))) + float(phi_offset_deg)
    return phi_deg % 360.0


def section12_bend_xz(pose: np.ndarray, section: int) -> np.ndarray:
    if section == 1:
        return _planned_bend_xz(pose, 0, 3)
    if section == 2:
        return _planned_bend_xz(pose, 1, 4)
    raise ValueError("section must be 1 or 2")


def apply_section12_bend_xz(pose: np.ndarray, section: int, bend_xz: np.ndarray) -> np.ndarray:
    """Write section 1 or 2 bend vector into pose Plane/Theta indices."""
    out = np.asarray(pose, dtype=float).copy()
    phi_deg, theta_deg = bend_xy_to_plane_theta_deg(np.asarray(bend_xz, dtype=float))
    if section == 1:
        out[0], out[3] = phi_deg, theta_deg
    elif section == 2:
        out[1], out[4] = phi_deg, theta_deg
    else:
        raise ValueError("section must be 1 or 2")
    return out


def solve_sections_12_inverse_kinematics(
    rope_home: np.ndarray,
    ball_center_mm: np.ndarray,
    base_mm: np.ndarray | None = None,
    *,
    phi_offset_deg: float = SECTION12_PHI_OFFSET_DEG,
    vision_to_arm_scale: np.ndarray | None = None,
) -> np.ndarray:
    """
    第 1–2 节逆运动学：倒立软体臂在 XZ 弯曲平面内朝球。

    ``ball_center_mm`` 为 soft_arm_center 下球心 [x,y,z] mm。
    """
    rope_home = np.asarray(rope_home, dtype=float)
    ball_center_mm = np.asarray(ball_center_mm, dtype=float).reshape(3)
    ball_arm = vision_center_to_arm_mm(ball_center_mm, vision_to_arm_scale)
    if base_mm is None:
        base_arm = DEFAULT_ARM_BASE_MM.copy()
    else:
        base_arm = vision_center_to_arm_mm(
            np.asarray(base_mm, dtype=float).reshape(3), vision_to_arm_scale
        )

    to_ball_xz = np.array(
        [ball_arm[0] - base_arm[0], ball_arm[2] - base_arm[2]],
        dtype=float,
    )
    dist = float(np.linalg.norm(to_ball_xz))
    if dist < 1e-6:
        x_mm, z_mm = 0.0, -1.0
    else:
        x_mm, z_mm = float(to_ball_xz[0]), float(to_ball_xz[1])

    phi_deg = plane_phi_from_xz_mm(x_mm, z_mm, phi_offset_deg)
    u_ball = np.array([x_mm, z_mm], dtype=float)
    norm = float(np.linalg.norm(u_ball))
    if norm > 1e-6:
        u_ball = u_ball / norm
    else:
        u_ball = np.array([0.0, -1.0], dtype=float)

    bend_scale = min(28.0, 8.0 + dist * 0.035)
    cap = MAX_SECTION12_POSE_DELTA

    pose = rope_home.copy()
    for section, weight, phi_idx, theta_idx in (
        (1, 0.55, 0, 3),
        (2, 0.45, 1, 4),
    ):
        bend_home = section12_bend_xz(rope_home, section)
        add_mag = float(np.clip(bend_scale * weight, 0.0, cap[theta_idx]))
        bend_target = bend_home + add_mag * u_ball
        # 朝 +X 球时保证 X 分量不减（避免 Plane 从 34° 收到 0° 导致 motor6 负步进）
        if u_ball[0] > 0.5 and bend_target[0] < bend_home[0]:
            bend_target[0] = bend_home[0] + add_mag * u_ball[0]
        if u_ball[0] < -0.5 and bend_target[0] > bend_home[0]:
            bend_target[0] = bend_home[0] + add_mag * u_ball[0]
        pose = apply_section12_bend_xz(pose, section, bend_target)
    return pose


def solve_section3_y_symmetric_motor14(
    home_pose: np.ndarray,
    ball_kinematic_mm: np.ndarray,
) -> tuple[int, int, np.ndarray]:
    """
    Section-3 grasp with fixed J-shape closure, mirrored across Y for ball +/-X.

    Uses motor1_4_test template: ball on -X -> m1 negative (+X bend); on +X -> m1 positive.
    """
    home_pose = np.asarray(home_pose, dtype=float)
    ball_kinematic_mm = np.asarray(ball_kinematic_mm, dtype=float)
    m1_mag = abs(int(REF_GRASP_MOTOR1_STEPS))
    m4 = int(REF_GRASP_MOTOR4_STEPS)
    bx = float(ball_kinematic_mm[0])
    # motor1+ -> -X；朝 +X 弯需 m1<0，朝 -X 弯需 m1>0
    m1 = m1_mag if bx <= 0.0 else -m1_mag
    m1, m4 = project_motor14_to_grasp_range(m1, m4)
    pose = section3_pose_from_grasp_motor14(home_pose, m1, m4)
    return m1, m4, pose


def solve_section3_grasp_motor14(
    home_pose: np.ndarray,
    ball_center_mm: np.ndarray,
    robot_base_mm: np.ndarray,
    approach: str = "side",
    vision_to_arm_scale: np.ndarray | None = None,
) -> tuple[int, int, np.ndarray]:
    """Kinematic grasp: bend toward ball with motor1/4 in the feasible envelope.

    ``home_pose`` should be the rope zero pose (section-3 angles cleared), matching
    the reference used for relative motor step commands on the bus.
    """
    home_pose = np.asarray(home_pose, dtype=float)
    delta = target_section3_bend_delta_for_ball(
        ball_center_mm, robot_base_mm, approach, vision_to_arm_scale
    )
    m1, m4 = bend_delta_to_motor14_steps(delta)
    m1, m4 = project_motor14_to_grasp_range(m1, m4)
    pose = section3_pose_from_grasp_motor14(home_pose, m1, m4)
    return m1, m4, pose


def bend_xy_to_plane_theta_deg(bend_xy: np.ndarray) -> tuple[float, float]:
    bend_xy = np.asarray(bend_xy, dtype=float)
    theta_deg = float(np.linalg.norm(bend_xy))
    phi_deg = float(np.degrees(np.arctan2(bend_xy[1], bend_xy[0])))
    if phi_deg < 0.0:
        phi_deg += 360.0
    return phi_deg, theta_deg


def apply_section3_bend_xy(pose: np.ndarray, bend_xy: np.ndarray) -> np.ndarray:
    out = np.asarray(pose, dtype=float).copy()
    out[SECTION3_PHI_IDX], out[SECTION3_THETA_IDX] = bend_xy_to_plane_theta_deg(bend_xy)
    return out


